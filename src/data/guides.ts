const VISIBLE_GUIDES = ALL_GUIDES.filter((g) => g.confirmed);

export function guideSlugs(): string[] {
  return VISIBLE_GUIDES.map((g) => g.slug);
}

export function guideSummaries(lang: Language): GuideSummary[] {
  return VISIBLE_GUIDES.map((g) => {
    const d = lang === 'zh' ? g.zh : g.en;
    return {
      slug: g.slug,
      href: localePath(lang, `/guides/${g.slug}/`),
      docId: d.docId,
      title: d.title,
      subtitle: d.subtitle,
      publishedAt: d.publishedAt,
      updatedAt: d.updatedAt,
      auditBasis: d.auditBasis,
      sampleLabel: d.sampleLabel,
      relatedProjectIds: d.relatedProjectIds,
      relatedVsSlugs: d.relatedVsSlugs,
    };
  });
}

export function guideArticle(slug: string, lang: Language): GuideArticleView | undefined {
  const entry = VISIBLE_GUIDES.find((g) => g.slug === slug);
  if (!entry) return undefined;
  const d = lang === 'zh' ? entry.zh : entry.en;
  return {
    slug: entry.slug,
    href: localePath(lang, `/guides/${entry.slug}/`),
    ...d,
  };
}

export function guidesForProject(projectId: string, lang: Language): GuideSummary[] {
  return guideSummaries(lang).filter((g) => g.relatedProjectIds.includes(projectId));
}
